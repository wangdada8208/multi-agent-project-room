"""Generate the pilot Hub response types without changing legacy OpenAPI."""

import argparse
import json
from pathlib import Path

from app.api.invite_schemas import RoomInviteView
from app.main import app
from app.permissions.schemas import RoomPermissionMember

ROOT = Path(__file__).resolve().parents[1]


def ts_type(schema: dict) -> str:
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(option) for option in schema["anyOf"])
    if schema["type"] == "array":
        return f"Array<{ts_type(schema['items'])}>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }[schema["type"]]


def interface(name: str, schema: dict) -> str:
    required = set(schema.get("required", []))
    fields = [
        f"  {field}{'' if field in required else '?'}: {ts_type(definition)};"
        for field, definition in schema["properties"].items()
    ]
    return "\n".join([f"export interface {name} {{", *fields, "}"])


def seat_response(openapi: dict, endpoint: str) -> dict:
    response = openapi["paths"][endpoint]["get"]["responses"]["200"]
    reference = response["content"]["application/json"]["schema"]["items"]["$ref"]
    return openapi["components"]["schemas"][reference.removeprefix("#/components/schemas/")]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files differ")
    args = parser.parse_args()
    openapi = app.openapi()
    components = openapi["components"]["schemas"]
    targets = {
        "frontend": {
            "RoomPermissionMember": RoomPermissionMember.model_json_schema(mode="serialization"),
            "RoomInviteView": RoomInviteView.model_json_schema(mode="serialization"),
            "SeatView": seat_response(openapi, "/api/v1/rooms/{room_id}/seats"),
            "ActivityItem": components["ActivityItem"],
            "CheckpointView": components["CheckpointView"],
        },
        "workers/xmtp-member": {
            "SeatPeer": seat_response(openapi, "/api/v1/rooms/{room_id}/seat-peers"),
            "HubSafeActivityEvent": components["SafeActivityEventIn"],
            "HubSignedCheckpoint": components["SignedCheckpointIn"],
            "HubActivityIngestResult": components["IngestResult"],
        },
    }
    stale = []
    for package, schemas in targets.items():
        path = ROOT / package / "src" / "hubContracts.generated.ts"
        exports = [interface(name, schema) for name, schema in schemas.items()]
        if package == "workers/xmtp-member":
            for name in ("HubSafeActivityEvent", "HubSignedCheckpoint"):
                keys = json.dumps(list(schemas[name]["properties"]))
                exports.append(f"export const {name}Fields = {keys} as const;")
        contents = "\n\n".join([
            "// Generated by scripts/generate_hub_contracts.py. Edit the backend response models.",
            *exports,
        ]) + "\n"
        if args.check:
            if not path.is_file() or path.read_text() != contents:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(contents)
    if stale:
        raise SystemExit(
            f"Stale Hub response types: {', '.join(stale)}. "
            "Run PYTHONPATH=backend python scripts/generate_hub_contracts.py."
        )


if __name__ == "__main__":
    main()
